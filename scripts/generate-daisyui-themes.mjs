/* eslint-env node */
/**
 * Emit six @plugin "daisyui/theme" blocks from src/styles/themes/*.ts
 * Run: node --experimental-strip-types scripts/generate-daisyui-themes.mjs
 */
import jitiFactory from 'jiti';

const createJiti = jitiFactory;
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const jiti = createJiti(import.meta.url);
const { connect } = jiti('../src/styles/themes/connect.ts');
const { modusClassic } = jiti('../src/styles/themes/modus-classic.ts');
const { modusModern } = jiti('../src/styles/themes/modus-modern.ts');

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const outPath = join(root, 'src/styles/generated/daisyui-themes.css');

const COLOR_KEYS = [
  'primary',
  'primary-content',
  'secondary',
  'secondary-content',
  'accent',
  'accent-content',
  'neutral',
  'neutral-content',
  'base-100',
  'base-200',
  'base-300',
  'base-content',
  'info',
  'info-content',
  'success',
  'success-content',
  'warning',
  'warning-content',
  'error',
  'error-content',
];

function toCssColor(value) {
  if (typeof value !== 'string') {
    return undefined;
  }
  return value.toLowerCase();
}

function themeBlock(name, palette, { defaultTheme = false, colorScheme }) {
  const lines = [];
  lines.push(`@plugin 'daisyui/theme' {`);
  lines.push(`  name: '${name}';`);
  if (defaultTheme) {
    lines.push(`  default: true;`);
  }
  lines.push(`  color-scheme: ${colorScheme};`);
  lines.push('');

  for (const key of COLOR_KEYS) {
    const cssKey = `--color-${key}`;
    const val = toCssColor(palette[key]);
    if (val) {
      lines.push(`  ${cssKey}: ${val};`);
    }
  }

  const roundedBtn = palette['--rounded-btn'] ?? '0.5rem';
  const roundedBox = palette['--rounded-box'] ?? '1rem';
  const roundedBadge = palette['--rounded-badge'] ?? '0.25rem';
  const borderBtn = palette['--border-btn'] ?? '1px';

  lines.push('');
  lines.push(`  --radius-field: ${roundedBtn};`);
  lines.push(`  --radius-box: ${roundedBox};`);
  lines.push(`  --radius-selector: ${roundedBadge};`);
  lines.push(`  --border: ${borderBtn};`);
  lines.push(`  --depth: 0;`);
  lines.push(`  --size-field: 0.25rem;`);
  lines.push(`  --size-selector: 0.25rem;`);
  lines.push('}');
  return lines.join('\n');
}

const themes = [
  {
    name: 'modus-modern-light',
    palette: modusModern.light,
    defaultTheme: true,
    colorScheme: 'light',
  },
  {
    name: 'modus-modern-dark',
    palette: modusModern.dark,
    colorScheme: 'dark',
  },
  {
    name: 'modus-classic-light',
    palette: modusClassic.light,
    colorScheme: 'light',
  },
  {
    name: 'modus-classic-dark',
    palette: modusClassic.dark,
    colorScheme: 'dark',
  },
  {
    name: 'connect-light',
    palette: connect.light,
    colorScheme: 'light',
  },
  {
    name: 'connect-dark',
    palette: connect.dark,
    colorScheme: 'dark',
  },
];

const header = `/* AUTO-GENERATED by scripts/generate-daisyui-themes.mjs — do not edit */\n`;
const body = themes
  .map((t) =>
    themeBlock(t.name, t.palette, {
      defaultTheme: t.defaultTheme,
      colorScheme: t.colorScheme,
    })
  )
  .join('\n\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, header + body + '\n', 'utf8');
console.log(`Wrote ${outPath} (${themes.length} themes)`);
