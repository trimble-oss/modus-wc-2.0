/* eslint-env node */

/**
 * Generate empty-state illustration SVG data as TypeScript string constants.
 * Reads SVGs from src/components/modus-wc-empty-state/assets/illustrations/
 * Tokenizes fills/strokes to CSS classes for theme support.
 *
 * Usage: node scripts/generate-illustration-data.js
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ASSETS_DIR = join(
  __dirname,
  '../src/components/modus-wc-empty-state/assets/illustrations'
);
const OUTPUT_PATH = join(
  __dirname,
  '../src/components/modus-wc-empty-state/illustration-svg-data.ts'
);

function mergeDuplicateClassAttributes(svg) {
  let result = svg;
  let previous = '';

  while (result !== previous) {
    previous = result;
    result = result.replace(
      /class="([^"]*)"\s+class="([^"]*)"/g,
      'class="$1 $2"'
    );
  }

  return result;
}

function tokenizeSvg(svg) {
  const tokenized = svg
    .replace(/\sstyle="[^"]*"/gi, '')
    .replace(
      /preserveAspectRatio="none"/gi,
      'preserveAspectRatio="xMidYMid meet"'
    )
    .replace(/\soverflow="visible"/gi, '')
    .replace(/\swidth="[^"]*"/gi, '')
    .replace(/\sheight="[^"]*"/gi, '')
    .replace(/fill="#0063A3"/gi, 'class="illustration-primary"')
    .replace(/fill="#217CBB"/gi, 'class="illustration-primary"')
    .replace(/fill="#DCEDF9"/gi, 'class="illustration-fill-pale"')
    .replace(/fill="#E1F0FF"/gi, 'class="illustration-fill-pale"')
    .replace(/fill="white"/gi, 'class="illustration-fill-surface"')
    .replace(/fill="#6A6E79"/gi, 'class="illustration-muted"')
    .replace(
      /stroke="#0063A3"/gi,
      'class="illustration-stroke-primary" stroke="currentColor"'
    )
    .replace(
      /stroke="#217CBB"/gi,
      'class="illustration-stroke-primary" stroke="currentColor"'
    )
    .replace(
      /stroke="white"/gi,
      'class="illustration-stroke-surface" stroke="currentColor"'
    );

  return mergeDuplicateClassAttributes(tokenized);
}

function walkSvgs(dir, prefix = '') {
  const result = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const rel = prefix ? `${prefix}/${entry}` : entry;
    if (statSync(full).isDirectory()) {
      result.push(...walkSvgs(full, rel));
    } else if (entry.endsWith('.svg')) {
      result.push({ rel, full });
    }
  }
  return result;
}

const files = walkSvgs(ASSETS_DIR);
const lines = [
  '// Auto-generated by scripts/generate-illustration-data.js',
  '// DO NOT EDIT MANUALLY',
  '',
  'export const ILLUSTRATION_SVGS: Record<string, string> = {',
];

for (const { rel, full } of files.sort((a, b) => a.rel.localeCompare(b.rel))) {
  const raw = readFileSync(full, 'utf8');
  const svg = tokenizeSvg(raw).replace(/\n/g, ' ').replace(/\s+/g, ' ').trim();
  const escaped = svg
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$/g, '\\$');
  lines.push(`  'illustrations/${rel}': \`${escaped}\`,`);
}

lines.push('};');
lines.push('');

writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf8');
globalThis.console.log(
  `Generated ${files.length} illustration SVG entries in illustration-svg-data.ts`
);
