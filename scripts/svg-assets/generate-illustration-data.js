/* eslint-env node */

/**
 * Generate empty-state illustration SVG data as TypeScript string constants.
 * Reads SVGs from src/svg-assets/illustrations/
 */

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { tokenizeIllustrationSvg } from './tokenize-illustration-svg.js';
import { walkSvgs } from './walk-svgs.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '../..');
const ASSETS_DIR = join(ROOT, 'src/svg-assets/illustrations');
const OUTPUT_PATH = join(
  ROOT,
  'src/svg-assets/generated/illustration-svg-data.ts'
);

const files = walkSvgs(ASSETS_DIR);
const lines = [
  '// Auto-generated by scripts/svg-assets/generate-illustration-data.js',
  '// DO NOT EDIT MANUALLY',
  '',
  'export const ILLUSTRATION_SVGS: Record<string, string> = {',
];

for (const { rel, full } of files.sort((a, b) => a.rel.localeCompare(b.rel))) {
  const raw = readFileSync(full, 'utf8');
  const svg = tokenizeIllustrationSvg(raw)
    .replace(/\n/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const escaped = svg
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$/g, '\\$');
  lines.push(`  'illustrations/${rel}': \`${escaped}\`,`);
}

lines.push('};');
lines.push('');

writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf8');
globalThis.console.log(
  `Generated ${files.length} illustration SVG entries in src/svg-assets/generated/illustration-svg-data.ts`
);
